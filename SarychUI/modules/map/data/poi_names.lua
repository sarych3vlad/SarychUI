-- Unknown keys resolve to themselves so the dataset always renders a name.
local identity = setmetatable({}, { __index = function(_, key) return key end })

function Maps:ApplyPoiLocale(locale)
	local pack = names[locale]
	if not pack then
		Maps.PoiNames = identity
		return
	end
	Maps.PoiNames = setmetatable({}, { __index = function(_, key) return pack[key] or key end })
end

Maps:ApplyPoiLocale(SarychUI.ResolveSavedUILocale and SarychUI.ResolveSavedUILocale() or GetLocale())
